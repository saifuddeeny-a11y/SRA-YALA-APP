# ------------------------------------------------------------------ helpers
def _fonts(rpr, size=None, bold=None, color=None):
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        rpr.insert(0, rf)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rf.set(qn(a), FONT)
    if size:
        for tag in ('w:sz', 'w:szCs'):
            el = rpr.find(qn(tag))
            if el is None:
                el = OxmlElement(tag)
                rpr.append(el)
            el.set(qn('w:val'), str(int(size * 2)))
    if bold:
        for tag in ('w:b', 'w:bCs'):
            if rpr.find(qn(tag)) is None:
                rpr.append(OxmlElement(tag))
    if color is not None:
        el = rpr.find(qn('w:color'))
        if el is None:
            el = OxmlElement('w:color')
            rpr.append(el)
        el.set(qn('w:val'), str(color))


def style_font(style, size, bold=False, color=None):
    _fonts(style.element.get_or_add_rPr(), size, bold, color)


def shade(cell, hex_fill):
    tcPr = cell._element.get_or_add_tcPr()
    sh = OxmlElement('w:shd')
    sh.set(qn('w:val'), 'clear')
    sh.set(qn('w:color'), 'auto')
    sh.set(qn('w:fill'), hex_fill)
    tcPr.append(sh)


def cell_margins(table, top=60, bottom=60, left=90, right=90):
    tblPr = table._element.tblPr
    m = OxmlElement('w:tblCellMar')
    for k, v in (('top', top), ('bottom', bottom), ('left', left), ('right', right)):
        e = OxmlElement('w:' + k)
        e.set(qn('w:w'), str(v))
        e.set(qn('w:type'), 'dxa')
        m.append(e)
    tblPr.append(m)


def set_widths(t, widths):
    t.autofit = False
    tblPr = t._element.tblPr
    lay = OxmlElement('w:tblLayout')
    lay.set(qn('w:type'), 'fixed')
    tblPr.append(lay)
    for i, w in enumerate(widths):
        t.columns[i].width = Cm(w)
        for c in t.columns[i].cells:
            c.width = Cm(w)


class Doc:
    def __init__(self, title, subtitle, landscape=False):
        self.d = Document()
        self.title = title
        sec = self.d.sections[0]
        if landscape:
            sec.orientation = WD_ORIENT.LANDSCAPE
            sec.page_width, sec.page_height = sec.page_height, sec.page_width
        sec.page_width, sec.page_height = (Cm(21), Cm(29.7)) if not landscape else (Cm(29.7), Cm(21))
        for side in ('left_margin', 'right_margin'):
            setattr(sec, side, Cm(2.2))
        sec.top_margin, sec.bottom_margin = Cm(2), Cm(2)
        st = self.d.styles
        style_font(st['Normal'], 11)
        st['Normal'].paragraph_format.space_after = Pt(4)
        st['Normal'].paragraph_format.line_spacing = 1.15
        for name, size, col in (('Title', 26, 'C2185B'), ('Heading 1', 18, 'C2185B'), ('Heading 2', 14, '1F1F26'), ('Heading 3', 12, '8C0F42')):
            style_font(st[name], size, True, col)
            st[name].paragraph_format.space_before = Pt(14 if name == 'Heading 1' else 10)
            st[name].paragraph_format.space_after = Pt(6)
        for name in ('List Bullet', 'List Number', 'Table Grid', 'Caption'):
            style_font(st[name], 11 if name != 'Caption' else 9.5)
        # header / footer
        hp = sec.header.paragraphs[0]
        hp.text = ''
        r = hp.add_run(title + '  ·  ' + ORG)
        _fonts(r._element.get_or_add_rPr(), 8.5, color='8A8590')
        hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        fp = sec.footer.paragraphs[0]
        fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = fp.add_run('หน้า ')
        _fonts(r._element.get_or_add_rPr(), 9, color='8A8590')
        self._field(fp, 'PAGE')
        self.cover(title, subtitle)

    def _field(self, p, code):
        r = p.add_run()
        _fonts(r._element.get_or_add_rPr(), 9, color='8A8590')
        for kind, txt in (('begin', None), (None, code), ('separate', None), (None, '1'), ('end', None)):
            if kind:
                e = OxmlElement('w:fldChar')
                e.set(qn('w:fldCharType'), kind)
                r._element.append(e)
            elif txt == code:
                e = OxmlElement('w:instrText')
                e.set(qn('xml:space'), 'preserve')
                e.text = ' %s ' % code
                r._element.append(e)
            else:
                t = OxmlElement('w:t')
                t.text = txt
                r._element.append(t)

    def cover(self, title, subtitle):
        for _ in range(5):
            self.d.add_paragraph()
        p = self.d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run('ระบบบริหารจัดการห้องทดลองสอน')
        _fonts(r._element.get_or_add_rPr(), 16, True, '45414B')
        p = self.d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run('ห้อง Micro Teaching')
        _fonts(r._element.get_or_add_rPr(), 30, True, 'C2185B')
        p = self.d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run('━━━━━━━━━━━━')
        _fonts(r._element.get_or_add_rPr(), 14, False, 'F2B230')
        p = self.d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(title)
        _fonts(r._element.get_or_add_rPr(), 22, True, '1F1F26')
        p = self.d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(subtitle)
        _fonts(r._element.get_or_add_rPr(), 13, False, '45414B')
        for _ in range(9):
            self.d.add_paragraph()
        for line, sz in ((ORG, 14), (VERSION, 11)):
            p = self.d.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(line)
            _fonts(r._element.get_or_add_rPr(), sz, sz > 12, '45414B')
        self.pb()

    # ---- content
    def runs(self, p, text, size=None, color=None):
        parts = re.split(r'(\*\*.+?\*\*)', text)
        for part in parts:
            if not part:
                continue
            bold = part.startswith('**') and part.endswith('**')
            r = p.add_run(part[2:-2] if bold else part)
            _fonts(r._element.get_or_add_rPr(), size, bold, color)
        return p

    def h1(self, t):
        self.d.add_heading(t, level=1)

    def h2(self, t):
        self.d.add_heading(t, level=2)

    def h3(self, t):
        self.d.add_heading(t, level=3)

    def p(self, t, align=None, size=None, color=None, after=None):
        para = self.d.add_paragraph()
        if align == 'c':
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        elif align == 'r':
            para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        elif align == 'j':
            para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        if after is not None:
            para.paragraph_format.space_after = Pt(after)
        return self.runs(para, t, size, color)

    def ul(self, items):
        for it in items:
            self.runs(self.d.add_paragraph(style='List Bullet'), it)

    def ol(self, items):
        for i, it in enumerate(items, 1):
            para = self.d.add_paragraph()
            para.paragraph_format.left_indent = Cm(0.9)
            para.paragraph_format.first_line_indent = Cm(-0.6)
            self.runs(para, '%d. %s' % (i, it))

    def table(self, header, rows, widths=None, size=10, head_fill='FBE3EE', zebra=True):
        t = self.d.add_table(rows=1, cols=len(header))
        t.style = 'Table Grid'
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        cell_margins(t)
        for i, h in enumerate(header):
            c = t.rows[0].cells[i]
            c.text = ''
            self.runs(c.paragraphs[0], '**' + h + '**' if h else '', size)
            shade(c, head_fill)
        for ri, row in enumerate(rows):
            cells = t.add_row().cells
            for i, v in enumerate(row):
                cells[i].text = ''
                lines = str(v).split('\n')
                self.runs(cells[i].paragraphs[0], lines[0], size)
                for ln in lines[1:]:
                    self.runs(cells[i].add_paragraph(), ln, size)
                if zebra and ri % 2 == 1:
                    shade(cells[i], 'FAF7F9')
        if widths:
            set_widths(t, widths)
        self.d.add_paragraph().paragraph_format.space_after = Pt(2)
        return t

    def note(self, text, fill='E5EFFA', color='1D3F66'):
        t = self.d.add_table(rows=1, cols=1)
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        cell_margins(t, 120, 120, 160, 160)
        c = t.rows[0].cells[0]
        shade(c, fill)
        lines = text.split('\n')
        self.runs(c.paragraphs[0], lines[0], 10.5, color)
        for ln in lines[1:]:
            self.runs(c.add_paragraph(), ln, 10.5, color)
        self.d.add_paragraph().paragraph_format.space_after = Pt(2)

    def img(self, name, caption, width=15.5):
        path = os.path.join(IMG, name)
        if not os.path.exists(path):
            self.p('[ไม่พบภาพ %s]' % name)
            return
        para = self.d.add_paragraph()
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        para.add_run().add_picture(path, width=Cm(width))
        cap = self.d.add_paragraph(style='Caption')
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        self.runs(cap, caption, 9.5, '75707C')

    def blank(self, label, dots=60):
        self.p(label + ' ' + '.' * dots, after=6)

    def pb(self):
        self.d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    def toc(self, items):
        self.h1('สารบัญ')
        for it in items:
            para = self.d.add_paragraph()
            para.paragraph_format.space_after = Pt(3)
            self.runs(para, it, 11.5)
        self.pb()

    def save(self, name):
        out = os.path.join(DOCS, name + '.docx')
        self.d.save(out)
        return out


def skills_from_code():
    src = open(os.path.join(APP, 'apps-script', 'Code.gs'), encoding='utf-8').read()
    out = []
    for m in re.finditer(r"\{ key: '(\w+)', name: '([^']+)', items: \[([^\]]+)\] \}", src):
        out.append((m.group(1), m.group(2), re.findall(r"'([^']+)'", m.group(3))))
    return out


def feedback_from_code():
    src = open(os.path.join(APP, 'apps-script', 'Code.gs'), encoding='utf-8').read()
    block = src.split('var FEEDBACK_ITEMS = [')[1].split('];')[0]
    return re.findall(r"'([^']+)'", block)


