def to_pdf(paths):
    try:
        subprocess.run(['soffice', '--headless', '--convert-to', 'pdf', '--outdir', DOCS] + paths, check=True, capture_output=True, timeout=600)
        return True
    except Exception as err:  # noqa: BLE001
        print('แปลง PDF ไม่สำเร็จ (ต้องติดตั้ง LibreOffice):', err)
        return False


