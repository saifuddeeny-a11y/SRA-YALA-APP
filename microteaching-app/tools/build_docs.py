def form_header(D, code, title):
    t = D.d.add_table(rows=1, cols=2)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c0, c1 = t.rows[0].cells
    D.runs(c0.paragraphs[0], '**ห้องทดลองสอน (Micro Teaching)**', 11)
    D.runs(c0.add_paragraph(), ORG, 10, '45414B')
    c1.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.RIGHT
    D.runs(c1.paragraphs[0], '**แบบ ' + code + '**', 12, 'C2185B')
    set_widths(t, [12, 4.6])
    D.p('**' + title + '**', align='c', size=16)


def checks(D, label, opts):
    D.p(label + '   ' + '    '.join('☐ ' + o for o in opts), after=6)


def signature(D, roles):
    t = D.d.add_table(rows=1, cols=len(roles))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    set_widths(t, [16.6 / len(roles)] * len(roles))
    for i, r in enumerate(roles):
        c = t.rows[0].cells[i]
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        dots = '.' * (46 if len(roles) < 3 else 30)
        for ln in ['', 'ลงชื่อ ' + dots, '(' + dots + ')', r, 'วันที่ ......../......../........']:
            q = c.add_paragraph()
            q.alignment = WD_ALIGN_PARAGRAPH.CENTER
            D.runs(q, ln, 10.5)


